// Educational norms. They are editable specifications, not validated industrial recipes.
const n = (id, name, unit, min, target, max, scaled = false) => ({
  id,
  name,
  unit,
  min,
  target,
  max,
  scaled,
  type: 'number',
  required: true,
});
const yes = (id, name) => ({ id, name, type: 'boolean', required: true });
const text = (id, name) => ({ id, name, type: 'text', required: true });
const cold = () => n('temperature', 'Температура в толще продукта', '°C', 0, 3, 4);
const hygiene = () => yes('hygiene', 'Санитарный допуск оборудования и инструмента подтверждён');
const take = (material, qty, source = 'process') => ({
  id: `in-${material}`,
  material,
  qty,
  source,
});
const give = (material, qty, destination = 'process', shelf) => ({
  id: `out-${material}`,
  material,
  qty,
  destination,
  ...(shelf ? { shelf } : {}),
});
const stock = (material, qty, shelf = 3) => give(material, qty, 'stock', shelf);
const op = (id, name, equipmentClass, inputs = [], outputs = [], parameters = [], loss) => ({
  id,
  name,
  kind: 'production',
  equipmentId: '',
  equipmentClass,
  inputs,
  outputs,
  parameters: [
    ...parameters,
    ...(loss != null
      ? [n('loss', 'Технологические потери', 'кг', 0, loss, Math.max(loss * 2, 5), true)]
      : []),
  ],
  ...(loss != null ? { massBalance: true, lossParameter: 'loss' } : {}),
});
const qc = (id, name, parameters) => ({ ...op(id, name, '', [], [], parameters), kind: 'quality' });
const process = (id, code, name, outputMaterial, baseQty, shelf, operations, description) => ({
  id,
  code,
  name,
  outputMaterial,
  baseQty,
  shelf,
  operations,
  description,
  revision: 1,
  lifecycle: 'published',
});

